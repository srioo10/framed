"""Cleaning + split audit for every dataset (PLAN Day 2). Writes results/cleaning_audit.{md,json}.

Usage: .venv/bin/python scripts/audit_clean.py [dataset ...]
"""
import gc
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from nids import clean, load, split  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "results"
DATASETS = ["unsw_official", "unsw_raw", "bot_iot", "ciciot_paper", "ciciot_csv", "ciciot_merged"]


def naive_overlap(df, dataset):
    """Share of test rows whose features (leak columns already removed) exactly match a training row,
    under the split the paper / dataset authors used, before any dedup."""
    feats = [c for c in clean.feature_columns(df) if c not in set(clean.LEAK_COLS[dataset])]
    h = clean.row_hash(df, feats)
    if "src" in df and set(df["src"].unique()) == {"train", "test"}:
        tr, te = np.flatnonzero(df["src"].to_numpy() == "train"), np.flatnonzero(df["src"].to_numpy() == "test")
        how = "official train/test files"
    else:
        tr, te = split.paper_split(df, seed=0)
        how = "random 80/20 (paper Algorithm 1)"
    return how, float(np.isin(h[te], h[tr]).mean())


def split_summary(df, seed=0):
    tr, va, te = split.grouped_split(df, seed)
    y, fam = df["y"].astype(str).to_numpy(), df["family"].astype(str).to_numpy()
    s = {
        "rows": {"train": len(tr), "val": len(va), "test": len(te)},
        "family_rows": {f: {"train": int((fam[tr] == f).sum()), "val": int((fam[va] == f).sum()),
                            "test": int((fam[te] == f).sum())} for f in sorted(set(fam))},
        "classes_missing_from_train": sorted(set(y) - set(y[tr])),
        "classes_missing_from_test": sorted(set(y) - set(y[te])),
    }
    if "group" in df:
        g = df["group"].to_numpy()
        s["groups"] = {"total": int(len(set(g))), "train": int(len(set(g[tr]))), "test": int(len(set(g[te])))}
    return s, tr


def audit(name):
    df = load.LOADERS[name]()
    how, overlap = naive_overlap(df, name)
    number_weight = df[["Number", "Weight"]] if "Weight" in df else None
    out, rep = clean.clean(df, name)
    del df
    gc.collect()
    s, tr = split_summary(out)
    if number_weight is not None:  # Number is dropped by clean(); check it on the raw rows behind train
        s["weight_follows_number_on_train"] = clean.weight_follows_number(number_weight.iloc[rep["kept_rows"][tr]])
    valid = rep["rows_in"] - rep["nonfinite"]
    res = {k: v for k, v in rep.items() if k not in ("per_class", "kept_rows")}
    res.update(dup_rate=rep["duplicates"] / valid, conflict_rate=rep["conflict_rows"] / valid,
               naive_split=how, naive_test_rows_in_train=overlap, split_seed0=s,
               per_class=rep["per_class"].to_dict(orient="index"))
    return res


def pct(x):
    return f"{100 * x:.1f}%"


def to_markdown(results):
    lines = ["# Cleaning and split audit", "",
             "Generated by `scripts/audit_clean.py`. Steps follow PREREG §3-4. Split = seed 0.", "",
             "## Summary", "",
             "| Dataset | Rows in | Non-finite | Label-conflict rows | Duplicates | Dup rate | Rows out "
             "| Naive split | Test rows already in train |",
             "|---|---:|---:|---:|---:|---:|---:|---|---:|"]
    for r in results.values():
        lines.append(f"| `{r['dataset']}` | {r['rows_in']:,} | {r['nonfinite']:,} | {r['conflict_rows']:,} "
                     f"| {r['duplicates']:,} | {pct(r['dup_rate'])} | {r['rows_out']:,} | {r['naive_split']} "
                     f"| {pct(r['naive_test_rows_in_train'])} |")
    lines += ["", "Dup rate = duplicates / finite rows. 'Test rows already in train' is measured before dedup, "
              "with identifier and known-leak columns already removed.", ""]
    for r in results.values():
        s = r["split_seed0"]
        lines += [f"## `{r['dataset']}`", "",
                  f"Split rows: train {s['rows']['train']:,} / val {s['rows']['val']:,} / test {s['rows']['test']:,}."]
        if "groups" in s:
            g = s["groups"]
            lines.append(f"Groups: {g['total']} total, {g['train']} in train, {g['test']} in test.")
        if s["classes_missing_from_train"] or s["classes_missing_from_test"]:
            lines.append(f"Classes absent from train: {s['classes_missing_from_train'] or 'none'}; "
                         f"absent from test: {s['classes_missing_from_test'] or 'none'}.")
        if "weight_follows_number_on_train" in s:
            lines.append(f"`Weight` is a deterministic function of `Number` on train: "
                         f"**{s['weight_follows_number_on_train']}**.")
        lines += ["", "| Family | Train | Val | Test |", "|---|---:|---:|---:|"]
        lines += [f"| {f} | {c['train']:,} | {c['val']:,} | {c['test']:,} |" for f, c in s["family_rows"].items()]
        lines += ["", "| Class | Rows in | Non-finite | Conflict | Duplicates | Rows out | Kept |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
        for cls, c in sorted(r["per_class"].items(), key=lambda kv: -kv[1]["rows_in"]):
            lines.append(f"| {cls} | {c['rows_in']:,} | {c['nonfinite']:,} | {c['conflict_rows']:,} "
                         f"| {c['duplicates']:,} | {c['rows_out']:,} | {pct(c['rows_out'] / c['rows_in'])} |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    names = sys.argv[1:] or DATASETS
    OUT.mkdir(exist_ok=True)
    path = OUT / "cleaning_audit.json"
    results = json.loads(path.read_text()) if path.exists() else {}
    for n in names:
        print("auditing", n, flush=True)
        results[n] = audit(n)
        path.write_text(json.dumps(results, indent=1, default=int))
        gc.collect()
    results = {n: results[n] for n in DATASETS if n in results}
    (OUT / "cleaning_audit.md").write_text(to_markdown(results))
    print("wrote", OUT / "cleaning_audit.md")
