"""Convert an engine model file (scripts/engine_export_b.py, read by certids.c load()) to a C header holding
`static const CertB CB_MODEL`, so the ESP32 keeps B in flash and never parses text (PREREG §9 DEPLOY).
Usage: python engine/model2h.py engine/build_transfer/model_b.txt firmware/gateway/main/model_transfer.h
"""
import sys


def main(src, dst):
    tok = open(src).read().split()
    pos = 0

    def take(n=1, f=float):
        nonlocal pos
        v = [f(x) for x in tok[pos:pos + n]]
        pos += n
        return v

    def word(w):
        nonlocal pos
        assert tok[pos] == w, (tok[pos], w)
        pos += 1

    word("certb")
    D, F, BI, K, M, W, L, mb = take(8, int)
    (tau,) = take()
    vec = {}
    for name in ("mu", "sd", "clo", "chi", "zero"):
        word(name)
        vec[name] = take(D)
    r = []
    for _ in range(M):
        word("r")
        r.append(take(D))
    layers = []
    for _ in range(L):
        word("layer")
        rows, cols = take(2, int)
        (ws,) = take()
        layers.append((rows, cols, ws, take(rows * cols, int), take(rows)))
    word("head")
    (hws,) = take()
    hw = [take(W * K, int) for _ in range(M)]
    hb = [take(K) for _ in range(M)]
    assert pos == len(tok), "trailing tokens"

    d = lambda v: "{" + ", ".join(repr(float(x)) for x in v) + "}"
    i = lambda v: "{" + ", ".join(str(int(x)) for x in v) + "}"
    out = [f"/* generated by engine/model2h.py from {src}; do not edit */", "#pragma once", '#include "certb.h"',
           "static const CertB CB_MODEL = {",
           f"  .D = {D}, .F = {F}, .BI = {BI}, .K = {K}, .M = {M}, .W = {W}, .L = {L},",
           f"  .mu = {d(vec['mu'])},", f"  .sd = {d(vec['sd'])},", f"  .clo = {d(vec['clo'])},",
           f"  .chi = {d(vec['chi'])},", f"  .zero = {i(vec['zero'])},",
           "  .r = {" + ", ".join(d(x) for x in r) + "},",
           "  .rows = " + i([l[0] for l in layers]) + ", .cols = " + i([l[1] for l in layers]) + ",",
           "  .w = {" + ", ".join(i(l[3]) for l in layers) + "},",
           "  .ws = " + d([l[2] for l in layers]) + ",",
           "  .b = {" + ", ".join(d(l[4]) for l in layers) + "},",
           "  .hw = {" + ", ".join(i(x) for x in hw) + "},", f"  .hws = {hws!r},",
           "  .hb = {" + ", ".join(d(x) for x in hb) + "},",
           f"  .tau = {tau!r}, .m_budget = {mb},", "};", ""]
    open(dst, "w").write("\n".join(out))


if __name__ == "__main__":
    main(*sys.argv[1:3])
